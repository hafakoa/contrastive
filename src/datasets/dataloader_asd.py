def balance_dataset(samples, labels, filenames, groups, domains):
  # First shuffle all data before splitting by class
  shuffle_idx = torch.randperm(len(samples))  # Random permutation of indices
  samples = samples[shuffle_idx]
  labels = labels[shuffle_idx]
  filenames = filenames[shuffle_idx]
  groups = groups[shuffle_idx]
  domains = domains[shuffle_idx]

  # Split

  """Generate balanced training set"""
  id0 = labels == 0
  id1 = labels == 1

  Samples_0, Samples_1 = samples[id0], samples[id1]
  Labels_0, Labels_1 = labels[id0], labels[id1]
  Filenames_0, Filenames_1 = filenames[id0], filenames[id1]
  Groups_0, Groups_1 = groups[id0], groups[id1]
  Domains_0, Domains_1 = domains[id0], domains[id1]

  if len(Samples_0) <= len(Samples_1):
      train_size = len(Samples_0)
  else:
      train_size = len(Samples_1)

  Samples_balanced = torch.cat((Samples_0[:train_size], Samples_1[:train_size]))
  Labels_balanced = torch.cat((Labels_0[:train_size], Labels_1[:train_size]))
  Filenames_balanced = torch.cat((Filenames_0[:train_size], Filenames_1[:train_size]))
  Groups_balanced = np.concatenate((Groups_0[:train_size], Groups_1[:train_size]))
  Domains_balanced = torch.cat((Domains_0[:train_size], Domains_1[:train_size]))

  return Samples_balanced, Labels_balanced, Filenames_balanced, Groups_balanced, Domains_balanced

