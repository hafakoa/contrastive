def individual_name(folder_path):
  folderPath = Path(folder_path)
  head_names = [f.stem.split('_')[0] for f in folderPath.glob('*.wav')]
  unique_headnames = list(set(head_names))
  return unique_headnames


def load_and_chunk_audio(wav_path, sample_rate, duration, hop_length):
    """Load .wav file and split into fixed-length chunks."""
    waveform, sr = librosa.load(wav_path, sr=sample_rate)
    chunk_size = int(sample_rate * duration)
    hop_size = int(sample_rate * hop_length)
    chunks = [waveform[i:i + chunk_size] for i in range(0, len(waveform) - chunk_size + 1, hop_size)]
    return torch.tensor(np.array(chunks), dtype=torch.float32)

def process_folder(filenames_to_process, labels, groups, domains, sample_rate=cfg.sample_rate, duration=cfg.duration, hop_length=cfg.hop_length, max_filename_length=30):
    """
    Process .wav files.
    """
    tokenizer = AutoTokenizer.from_pretrained("bert-base-uncased")
    all_chunks = []
    all_labels = []
    all_filenames = []
    all_groups = []
    all_domains = []
    file_count = 0
    files_by_child = defaultdict(list)
    #filenames_to_process, labels, groups = build_dataset(data_dir)

    # Boucle de traitement
    from tqdm import tqdm

    for audio_path, label, group, domain in tqdm(
            zip(filenames_to_process, labels, groups, domains),
            total=len(filenames_to_process),
            desc="Processing audio files"
    ):
        file_count += 1
        chunks = load_and_chunk_audio(audio_path, sample_rate, duration, hop_length)

        if chunks is None or len(chunks) == 0:
            continue

        num_chunks = len(chunks)
        filename = os.path.basename(audio_path)
        tokenized = tokenizer(filename, max_length=max_filename_length,
                              padding="max_length", truncation=True,
                              return_tensors="pt")["input_ids"].squeeze(0)

        filename_map[tuple(tokenized.tolist())] = filename

        all_chunks.append(chunks)
        all_labels.append(torch.full((num_chunks,), label, dtype=torch.long))
        all_filenames.append(tokenized.repeat(num_chunks, 1))
        all_groups.extend([group] * num_chunks)
        all_domains.append(torch.full((num_chunks,), domain, dtype=torch.long))
        #print(f"file processed: {file_count}")


    # Finalisation
    all_chunks = torch.cat(all_chunks, dim=0) if all_chunks else torch.tensor([])
    all_labels = torch.cat(all_labels, dim=0) if all_labels else torch.tensor([])
    all_filenames = torch.cat(all_filenames, dim=0) if all_filenames else torch.tensor([])
    all_groups = np.array(all_groups)
    #all_groups = torch.cat(all_groups, dim=0) if all_groups else torch.tensor([])
    all_domains = torch.cat(all_domains, dim=0) if all_domains else torch.tensor([])

    print(f"\nTOTAL CHUNKS : {len(all_chunks)}")
    print(f"TOTAL LABELS : {len(all_labels)}")
    print(f"TOTAL FILENAMES : {len(all_filenames)}\n")
    print(f"TOTAL GROUPS : {len(all_groups)}\n")
    print(f"TOTAL DOMAINS : {len(all_domains)}\n")

    return all_chunks, all_labels, all_filenames, all_groups, all_domains, filename_map

