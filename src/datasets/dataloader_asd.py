class BalancedSubjectBatchSampler(Sampler):

    def __init__(
        self,
        groups,
        labels,
        batch_size=64,
        subjects_per_class=None,
        drop_last=True
    ):

        self.groups = np.array(groups)
        self.labels = np.array(labels)

        self.batch_size = batch_size
        self.drop_last = drop_last

        # ==================================================
        # Build:
        # subject -> chunk indices
        # ==================================================

        self.subject_to_indices = defaultdict(list)

        for idx, subject in enumerate(self.groups):
            self.subject_to_indices[subject].append(idx)

        # ==================================================
        # Subject-level labels
        # ==================================================

        self.subject_to_label = {}

        for idx, subject in enumerate(self.groups):
            self.subject_to_label[subject] = self.labels[idx]

        # ==================================================
        # Separate subjects by class
        # ==================================================

        self.class_subjects = defaultdict(list)

        for subject, label in self.subject_to_label.items():
            self.class_subjects[label].append(subject)

        # ==================================================
        # ASD vs non-ASD balancing
        # ==================================================

        if subjects_per_class is None:
            self.subjects_per_class = batch_size // 2
        else:
            self.subjects_per_class = subjects_per_class

        self.num_batches = min(
            len(self.class_subjects[0]),
            len(self.class_subjects[1])
        ) // self.subjects_per_class

    def __iter__(self):

        num_batches = len(self)

        for _ in range(num_batches):

            selected_subjects_0 = random.sample(
                self.class_subjects[0],
                min(self.subjects_per_class,
                    len(self.class_subjects[0]))
            )

            selected_subjects_1 = random.sample(
                self.class_subjects[1],
                min(self.subjects_per_class,
                    len(self.class_subjects[1]))
            )

            selected_subjects = (
                selected_subjects_0 +
                selected_subjects_1
            )

            batch_indices = []

            for subject in selected_subjects:

                candidate_indices = self.subject_to_indices[subject]

                chosen_idx = random.choice(candidate_indices)

                batch_indices.append(chosen_idx)

            random.shuffle(batch_indices)

            yield batch_indices

    def __len__(self):

        return max(
            len(self.groups) // self.batch_size,
            1
        )

