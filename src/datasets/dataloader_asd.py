class Load_Dataset(Dataset):
    def __init__(self, dataset):
        super(Load_Dataset, self).__init__()
        #self.training_mode = training_mode
        X_train = dataset["samples"]
        y_train = dataset["labels"]
        f_train = dataset["filenames"]
        g_train = dataset["groups"]
        d_train = dataset["domains"]

        data = list(zip(X_train, y_train, f_train, g_train, d_train))
        np.random.shuffle(data)
        X_train, y_train, f_train, g_train, d_train = zip(*data)
        X_train, y_train, f_train, d_train = torch.stack(list(X_train), dim=0), torch.stack(list(y_train), dim=0), torch.stack(list(f_train), dim=0), torch.stack(list(d_train), dim=0)

        if len(X_train.shape) < 3:
            X_train = X_train.unsqueeze(2)

        if X_train.shape.index(min(X_train.shape)) != 1:  # make sure the Channels in second dim
            X_train = X_train.permute(0, 2, 1)

        """Align the TS length between source and target datasets"""
        X_train = X_train[:, :1, :cfg.TSlength_aligned] # take the first 1600 samples for voice for example

        if isinstance(X_train, np.ndarray):
            self.x_data = torch.from_numpy(X_train)
            self.y_data = torch.from_numpy(y_train).long()
            self.f_data = torch.from_numpy(f_train).long()
            self.groups = torch.from_numpy(g_train).long()
            self.d_data = torch.from_numpy(d_train).long()
        else:
            self.x_data = X_train
            self.y_data = y_train
            self.f_data = f_train
            self.groups = np.array(g_train)
            self.d_data = d_train

        """Transfer x_data to Frequency Domain. If use fft.fft, the output has the same shape; if use fft.rfft,
        the output shape is half of the time window."""

        window_length = self.x_data.shape[-1]
        self.x_data_f = fft.fft(self.x_data).abs()        #/(window_length) # rfft for real value inputs.
        self.len = X_train.shape[0]

        """Augmentation"""                                # no need to apply Augmentations in other modes
        self.aug1 = DataTransform_TD(self.x_data)         # if needed replace with DataTransform_TD_bank()
        self.aug1_f = DataTransform_FD(self.x_data_f)     # [7360, 1, 90]

    def __getitem__(self, index):
        return self.x_data[index], self.y_data[index], self.aug1[index],  \
                   self.x_data_f[index], self.aug1_f[index], self.f_data[index], self.d_data[index]

    def __len__(self):
        return self.len


