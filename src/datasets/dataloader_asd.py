def extract_info(filename):
    stem = Path(filename).stem
    # child_id = avant "_"
    child_id = stem.split("_")[0]
    prefix = child_id.lower()
    if prefix.startswith("asd"):   #SK-ASD
        label = 1
        original_label = "asd"
    elif prefix.startswith("p"):   # ASD-RECANVO
        label = 1
        original_label = "p"
    elif prefix.startswith("f"):   # UCLASS F
        label = 0
        original_label = "f"
    elif prefix.startswith("m"):   # UCLASS M
        label = 0
        original_label = "m"
    elif prefix.startswith("td"):   #SKTD
        label = 0
        original_label = "td"
    elif prefix.startswith("adhd"):  #SK-ADHD
        label = 0
        original_label = "adhd"
    else:
        raise ValueError(f"Unknown prefix in file: {filename}")

    return child_id, label, original_label


