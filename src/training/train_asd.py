          """Produce embeddings"""
          h_t, z_t, h_f, z_f = model(data, data_f)
          h_t_aug, z_t_aug, h_f_aug, z_f_aug = model(aug1, aug1_f)

          z_t = F.normalize(z_t, dim=1)
          z_f = F.normalize(z_f, dim=1)
