def model_validate(model, valid_dl, device, classifier):

    model.eval()
    classifier.eval()

    criterion = nn.CrossEntropyLoss()

    total_loss = []
    total_acc = []

    with torch.no_grad():

        for data, labels, _, data_f, _, _, _ in valid_dl:

            data = data.float().to(device)
            labels = labels.long().to(device)
            data_f = data_f.float().to(device)

            # Forward pass
            h_t, z_t, h_f, z_f = model(data, data_f)

            z_t = F.normalize(z_t, dim=1)
            z_f = F.normalize(z_f, dim=1)

            # SupCon embeddings
            features_supcon = torch.cat(
                [z_t.unsqueeze(1), z_f.unsqueeze(1)],
                dim=1
            )

            criterion_supcon = SupConLoss()
            l_supcon = criterion_supcon(features_supcon, labels)

            # Classification
            fea_concat = torch.cat((z_t, z_f), dim=1)

            predictions = classifier(fea_concat)

            loss_cls = criterion(predictions, labels)

            alpha = 1.0
            loss = alpha * l_supcon + loss_cls

            acc = labels.eq(
                predictions.argmax(dim=1)
            ).float().mean()

            total_loss.append(loss.item())
            total_acc.append(acc.item())

    avg_loss = np.mean(total_loss)
    avg_acc = np.mean(total_acc)

    print(f' Validation: loss={avg_loss:.4f} | Acc={avg_acc*100:.2f}')

    return avg_loss, avg_acc


def model_test_individual_level(model, testdl, device, classifier, filename_map):
    model.eval()
    classifier.eval()

    # Initialize accumulators
    all_preds = []
    all_labels = []
    all_filenames = []
    all_probs = []

    with torch.no_grad():
        for data, labels, _, data_f, _, filenames, _ in testdl:
            data, labels = data.float().to(device), labels.long().to(device)
            data_f = data_f.float().to(device)

            # Forward pass
            h_t, z_t, h_f, z_f = model(data, data_f)
            z_t = F.normalize(z_t, dim=1)           # without F.normalize to test
            z_f = F.normalize(z_f, dim=1)
            fea_concat = torch.cat((z_t, z_f), dim=1)
            logits = classifier(fea_concat)
            probs = torch.softmax(logits, dim=1)

            # Store batch results
            all_preds.append(logits.detach().cpu().numpy())
            all_probs.append(probs.detach().cpu().numpy())
            all_labels.append(labels.detach().cpu().numpy())
            all_filenames.extend([tuple(t.tolist()) for t in filenames])

    # Concatenate all batch results
    pred_numpy = np.concatenate(all_preds, axis=0)
    probs_numpy = np.concatenate(all_probs, axis=0)
    labels_numpy = np.concatenate(all_labels, axis=0)

    # Group predictions by individual ID
    individual_results = defaultdict(lambda: {'preds': [], 'probs': [], 'labels': [], 'files': set()})
    individual_class_counts = defaultdict(int)  # Track class distribution

    for token_ids, pred, prob, label in zip(all_filenames, pred_numpy, probs_numpy, labels_numpy):
        original_name = filename_map.get(token_ids, "unknown")
        if original_name == "unknown":
            continue

        individual_id = get_individual_id(original_name)
        individual_results[individual_id]['preds'].append(pred)
        individual_results[individual_id]['probs'].append(prob)
        individual_results[individual_id]['labels'].append(label)
        individual_results[individual_id]['files'].add(original_name)

    # Calculate individual-level predictions and count class distribution
    individual_acc = {}
    all_individual_probs = []
    all_individual_labels = []
    class_distribution = defaultdict(int)  # Count individuals per class

    for ind_id, data in individual_results.items():
        # Verify consistent ground truth
        unique_labels = set(data['labels'])
        if len(unique_labels) > 1:
            print(f"Warning: Individual {ind_id} has inconsistent labels")

        true_label = data['labels'][0]
        class_distribution[true_label] += 1

        # Aggregate predictions (majority vote)
        chunk_decisions = np.argmax(data['preds'], axis=1)
        majority_pred = np.bincount(chunk_decisions).argmax()

        # Confidence score (mean probability)
        mean_probs = np.mean(data['probs'], axis=0)
        confidence = mean_probs[majority_pred]

        # Store for overall metrics
        all_individual_probs.append(mean_probs)
        all_individual_labels.append(true_label)

        individual_acc[ind_id] = {
            'prediction': majority_pred,
            'true_label': true_label,
            'confidence': confidence,
            'num_files': len(data['files']),
            'num_chunks': len(data['preds']),
            'agreement': f"{np.mean(chunk_decisions == majority_pred):.1%}",
            'probabilities': mean_probs
        }

    # Calculate metrics
    y_true = np.array([v['true_label'] for v in individual_acc.values()])
    y_pred = np.array([v['prediction'] for v in individual_acc.values()])
    y_probs = np.array([v['probabilities'] for v in individual_acc.values()])

    # Binary classification metrics (assuming binary classification)
    if y_probs.shape[1] == 2:  # Binary case
        precision = precision_score(y_true, y_pred, zero_division=0)
        recall = recall_score(y_true, y_pred)
        f1 = f1_score(y_true, y_pred)
        auroc = roc_auc_score(y_true, y_probs[:, 1])
        auprc = average_precision_score(y_true, y_probs[:, 1])
    else:  # Multiclass case
        precision = precision_score(y_true, y_pred, average='weighted', zero_division=0)
        recall = recall_score(y_true, y_pred, average='weighted')
        f1 = f1_score(y_true, y_pred, average='weighted')
        try:
            auroc = roc_auc_score(y_true, y_probs, multi_class='ovo', average='weighted')
            auprc = average_precision_score(y_true, y_probs, average='weighted')
        except ValueError as e:
            print(f"Couldn't calculate AUROC/AUPRC: {e}")
            auroc = float('nan')
            auprc = float('nan')

    accuracy = np.mean(y_true == y_pred)

    # Get class names (assuming 0=NonASD, 1=ASD for binary case)
    class_names = {0: 'NonASD', 1: 'ASD'} if len(class_distribution) == 2 else \
                 {i: f'Class_{i}' for i in class_distribution.keys()}

    # Format class distribution string
    dist_str = ", ".join([f"{count} {class_names[cls]}" for cls, count in sorted(class_distribution.items())])

    #print("\nIndividual PERFORMANCE Metrics:")
    print(f"Individuals evaluated: {len(individual_acc)} ({dist_str})")
    print('MLP Testing: Acc=%.4f| Precision = %.4f | Recall = %.4f | F1 = %.4f | AUROC= %.4f | AUPRC=%.4f')
#           % (accuracy*100, precision * 100, recall * 100, f1 * 100, auroc*100, auprc*100))

    metrics = {
        'accuracy': accuracy,
        'precision': precision,
        'recall': recall,
        'f1': f1,
        'auroc': auroc,
        'auprc': auprc,
        'num_individuals': len(individual_acc),
        'class_distribution': dict(class_distribution),
        'class_names': class_names,
        'y_true': y_true,
        'y_pred': y_pred
    }

    return individual_acc, metrics, dist_str