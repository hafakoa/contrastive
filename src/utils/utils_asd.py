class MetricTracker:
    def __init__(self):
        self.best_metrics = None
        self.best_epoch = 0
        self.best_score = -1

    def update(self, metrics, epoch, key='accuracy'):
        """Update best metrics based on selected key metric"""
        current_score = metrics[key]

        if current_score > self.best_score:
            self.best_score = current_score
            self.best_epoch = epoch
            self.best_metrics = metrics.copy()
            #print(f"New best {key} at epoch {epoch}: {current_score:.4f}")

    def print_best(self, metrics=None): # Le paramètre metrics est optionnel ici car on veut le BEST
        """Print and return the best metrics achieved"""
        if self.best_metrics is None:
            print("No metrics tracked yet.")
            return None

        print(f"--- Best Results Achieved at epoch {self.best_epoch} ---")
        # On appelle print_metrics et on retourne son résultat
        return print_metrics(self.best_metrics, self.best_epoch)


def print_metrics(metrics, epoch=None):
    """Print metrics dictionary in a readable format"""
    # Main metrics

    print(f"-----MLP Best Testing Perf at epoch {epoch} : "
      f"Acc={metrics['accuracy']*100:.4f}| "
      f"Precision={metrics['precision']*100:.4f} | "
      f"Recall={metrics['recall']*100:.4f} | "
      f"F1={metrics['f1']*100:.4f} | "
      f"AUROC={metrics['auroc']*100:.4f} | "
      f"AUPRC={metrics['auprc']*100:.4f}")
    return metrics

