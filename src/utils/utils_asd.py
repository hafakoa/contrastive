def get_file_type(filename):
    """Détermine si le fichier commence par un chiffre ou une lettre."""
    if not filename or not isinstance(filename, str):
        return "Inconnu"

    first_char = filename[0]
    if first_char.isdigit():
        return "Chiffre"
    elif first_char.isalpha():
        return "Lettre"
    else:
        return "Autre"

