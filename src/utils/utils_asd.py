def print_metrics_prediction(output_csv_path):
    """Charge le CSV et affiche les statistiques d'exactitude par groupe."""
    # 1. Charger le fichier CSV
    try:
        df = pd.read_csv(output_csv_path)
    except FileNotFoundError:
        print(f"Erreur : Le fichier {output_csv_path} est introuvable.")
        return

    # 2. Appliquer la fonction pour créer une nouvelle colonne de groupe
    df['group_type'] = df['filename'].apply(get_file_type)

    # 3. Calculer les statistiques par groupe
    # On calcule le nombre de corrects et le total par groupe
    summary = df.groupby('group_type').agg(
        Total=('status', 'count'),
        Corrects=('status', lambda x: (x == 'CORRECT').sum())
    )

    # 4. Calculer le pourcentage
    summary['Accuracy (%)'] = (summary['Corrects'] / summary['Total']) * 100

    # Affichage des résultats
    print("\n" + "="*50)
    print("--- ANALYSE DE L'EXACTITUDE PAR TYPE DE FICHIER ---")
    print("="*50)

    # Affichage détaillé pour le rapport
    for group, row in summary.iterrows():
        print(f"\nGroupe '{group}':")
        print(f"  - Rapport   : {int(row['Corrects'])} / {int(row['Total'])} corrects")
        print(f"  - Précision : {row['Accuracy (%)']:.2f}%")
